/**
 * lib/studio/generators.ts — parameterised Verilog building blocks for /studio/generators:
 * LFSR, CRC, clock divider, PWM, debouncer, FIFO, Gray counter, ROM, edge detector, shift
 * register and binary-to-BCD. Each has a cycle-accurate model here; its testbench drives the
 * same stimulus and checks every output against the model on every cycle.
 * Self-check: scripts/generators.check.ts; scripts/studio-sim.check.ts runs them on Icarus.
 */

export type Values = Record<string, number | string>;
export interface Param {
  key: string; label: string; kind: "int" | "hex" | "text"; default: number | string;
  min?: number; max?: number; hint?: string;
}
export interface Generated { module: string; design: string; testbench: string; notes: string[] }
export interface Generator {
  id: string; title: string; blurb: string; params: Param[];
  presets?: { label: string; values: Values }[];
  build: (v: Values) => Generated | string;
}

// ── Helpers ──────────────────────────────────────────────────────────────────

type V = Record<string, bigint>;
interface Port { name: string; width: number }
interface Cycle { set: V; expect: V; note?: string }

const big = (x: number | bigint) => BigInt(x);
const mask = (w: number) => (1n << big(w)) - 1n;
/** Bits to hold the values 0 … n. */
export const bitsFor = (n: number) => Math.max(1, Math.ceil(Math.log2(n + 1)));
const lit = (w: number, v: bigint) => `${w}'h${(v & mask(w)).toString(16)}`;
const decl = (w: number) => (w > 1 ? `[${w - 1}:0] ` : "");
const isPow2 = (n: number) => Number.isInteger(n) && n > 0 && (n & (n - 1)) === 0;
const num = (v: Values, k: string) => Number(v[k]);
const header = (what: string) => `// Generated by BitFlow Studio: ${what}\n`;
function rng(seed = 12345) {
  let s = seed >>> 0;
  return () => { s = (Math.imul(s, 1664525) + 1013904223) >>> 0; return s / 2 ** 32; };
}
/** "0x1021" or "1021" (hex) as a BigInt, or null. */
function hexValue(s: number | string | undefined): bigint | null {
  const t = String(s ?? "").trim().replace(/_/g, "");
  if (/^0x[0-9a-f]+$/i.test(t)) return BigInt(t);
  if (/^[0-9a-f]+$/i.test(t)) return BigInt(`0x${t}`);
  return null;
}

/** A testbench that applies each cycle's inputs, clocks once (or waits, for combinational logic) and checks the outputs. */
function vectorTb(mod: string, ins: Port[], outs: Port[], cycles: Cycle[], clocked: boolean, what: string): string {
  const tb = `tb_${mod}`;
  const prev: V = {};
  const body = cycles.map((cy, i) => {
    const sets = ins.filter((p) => cy.set[p.name] !== undefined && prev[p.name] !== cy.set[p.name]).map((p) => `${p.name} = ${lit(p.width, cy.set[p.name])};`);
    Object.assign(prev, cy.set);
    const checks = outs.filter((p) => cy.expect[p.name] !== undefined).map((p) => `expect_${p.name}(${lit(p.width, cy.expect[p.name])}, ${i});`);
    return `        ${[...sets, clocked ? "@(posedge clk); #1;" : "#5;", ...checks].join(" ")}${cy.note ? `   // ${cy.note}` : ""}`;
  });
  return `\`timescale 1ns / 1ps
// Generated by BitFlow Studio: ${what}.
// Every cycle's outputs are checked against a reference model of the design.
module ${tb};
${clocked ? "    reg clk = 1'b0;\n" : ""}${ins.map((p) => `    reg  ${decl(p.width)}${p.name};`).join("\n")}
${outs.map((p) => `    wire ${decl(p.width)}${p.name};`).join("\n")}
    integer errors = 0;

    ${mod} dut (${[...(clocked ? ["clk"] : []), ...ins.map((p) => p.name), ...outs.map((p) => p.name)].map((n) => `.${n}(${n})`).join(", ")});
${clocked ? "    always #5 clk = ~clk;\n" : ""}
${outs.map((p) => `    task expect_${p.name};
        input ${decl(p.width)}v;
        input [31:0] c;
        if (${p.name} !== v) begin
            $display("FAIL: cycle %0d: ${p.name} = %0h, expected %0h", c, ${p.name}, v);
            errors = errors + 1;
        end
    endtask`).join("\n")}

    initial begin
        $dumpfile("wave.vcd");
        $dumpvars(0, ${tb});
${body.join("\n")}
        if (errors == 0) $display("ALL TESTS PASSED");
        else $display("TESTS FAILED: %0d error(s)", errors);
        $finish;
    end
endmodule
`;
}

// ── LFSR ─────────────────────────────────────────────────────────────────────

/** Maximal-length taps (Xilinx XAPP052), bit numbers counted from 1. */
export const LFSR_TAPS: Record<number, number[]> = {
  3: [3, 2], 4: [4, 3], 5: [5, 3], 6: [6, 5], 7: [7, 6], 8: [8, 6, 5, 4], 9: [9, 5], 10: [10, 7], 11: [11, 9], 12: [12, 6, 4, 1],
  13: [13, 4, 3, 1], 14: [14, 5, 3, 1], 15: [15, 14], 16: [16, 15, 13, 4], 17: [17, 14], 18: [18, 11], 19: [19, 6, 2, 1], 20: [20, 17],
  21: [21, 19], 22: [22, 21], 23: [23, 18], 24: [24, 23, 22, 17], 25: [25, 22], 26: [26, 6, 2, 1], 27: [27, 5, 2, 1], 28: [28, 25],
  29: [29, 27], 30: [30, 6, 4, 1], 31: [31, 28], 32: [32, 22, 2, 1],
};
/** One step of the Fibonacci LFSR: shift left; the XOR of the tap bits enters at bit 0. */
export function lfsrNext(q: bigint, w: number): bigint {
  const fb = LFSR_TAPS[w].reduce((x, t) => x ^ ((q >> big(t - 1)) & 1n), 0n);
  return ((q << 1n) | fb) & mask(w);
}

const lfsr: Generator = {
  id: "lfsr", title: "LFSR (pseudo-random)", blurb: "A maximal-length linear-feedback shift register: it visits all 2ⁿ−1 non-zero states. Test patterns, scramblers and cheap random numbers.",
  params: [{ key: "width", label: "Width", kind: "int", default: 8, min: 3, max: 32 }, { key: "seed", label: "Seed (hex, not 0)", kind: "hex", default: "1" }],
  build: (v) => {
    const w = num(v, "width"), seed = hexValue(v.seed);
    if (!LFSR_TAPS[w]) return "Widths from 3 to 32.";
    if (seed === null || (seed & mask(w)) === 0n) return "The seed must be a non-zero hex number: an all-zero LFSR stays at zero.";
    const mod = `lfsr${w}`, taps = LFSR_TAPS[w];
    const design = `${header(`${w}-bit Fibonacci LFSR, taps ${taps.join(", ")}: a period of ${2 ** w - 1} states.`)}module ${mod} #(parameter [${w - 1}:0] SEED = ${lit(w, seed)}) (
    input  wire        clk,
    input  wire        rst,        // synchronous, active high: load SEED
    input  wire        en,
    output reg  ${decl(w)}q
);
    wire feedback = ${taps.map((t) => `q[${t - 1}]`).join(" ^ ")};
    always @(posedge clk)
        if (rst)     q <= SEED;
        else if (en) q <= {q[${w - 2}:0], feedback};
endmodule
`;
    const cycles: Cycle[] = [];
    let q = 0n;
    const n = Math.min(2 ** w + 8, 300);
    for (let i = 0; i < n; i++) {
      const rst = i < 2 ? 1n : 0n, en = i % 37 === 20 ? 0n : 1n;
      q = rst ? seed & mask(w) : en ? lfsrNext(q, w) : q;
      cycles.push({ set: { rst, en }, expect: { q }, note: rst ? "reset" : en ? undefined : "en = 0: hold" });
    }
    return {
      module: mod, design, testbench: vectorTb(mod, [{ name: "rst", width: 1 }, { name: "en", width: 1 }], [{ name: "q", width: w }], cycles, true, `${n} cycles of the ${w}-bit LFSR`),
      notes: [`Period ${2 ** w - 1}: every state except all zeros appears once.`, "For a pseudo-random bit stream, use q[0]."],
    };
  },
};

// ── CRC ──────────────────────────────────────────────────────────────────────

/** Bit-serial CRC (MSB first, not reflected): the register after each message bit (before the final XOR). */
export function crcBits(bytes: number[], width: number, poly: bigint, init: bigint): bigint[] {
  let c = init & mask(width);
  const states: bigint[] = [];
  for (const byte of bytes) for (let b = 7; b >= 0; b--) {
    const fb = ((c >> big(width - 1)) & 1n) ^ big((byte >> b) & 1);
    c = ((c << 1n) & mask(width)) ^ (fb ? poly & mask(width) : 0n);
    states.push(c);
  }
  return states;
}

const crc: Generator = {
  id: "crc", title: "CRC (serial)", blurb: "A bit-serial cyclic redundancy check, one data bit per clock, MSB first. Matches the standard CRCs that don't reflect their bits.",
  params: [
    { key: "width", label: "Width", kind: "int", default: 16, min: 3, max: 32 },
    { key: "poly", label: "Polynomial (hex)", kind: "hex", default: "1021" },
    { key: "init", label: "Initial value (hex)", kind: "hex", default: "FFFF" },
    { key: "xorout", label: "Final XOR (hex)", kind: "hex", default: "0" },
    { key: "message", label: "Test message", kind: "text", default: "123456789" },
  ],
  presets: [
    { label: "CRC-8/SMBUS", values: { width: 8, poly: "07", init: "0", xorout: "0" } },
    { label: "CRC-16/CCITT-FALSE", values: { width: 16, poly: "1021", init: "FFFF", xorout: "0" } },
    { label: "CRC-16/XMODEM", values: { width: 16, poly: "1021", init: "0", xorout: "0" } },
    { label: "CRC-32/MPEG-2", values: { width: 32, poly: "04C11DB7", init: "FFFFFFFF", xorout: "0" } },
    { label: "CRC-32/BZIP2", values: { width: 32, poly: "04C11DB7", init: "FFFFFFFF", xorout: "FFFFFFFF" } },
  ],
  build: (v) => {
    const w = num(v, "width"), poly = hexValue(v.poly), init = hexValue(v.init), xorout = hexValue(v.xorout);
    if (!(w >= 3 && w <= 32)) return "Widths from 3 to 32.";
    if (poly === null || init === null || xorout === null) return "The polynomial, initial value and final XOR are hex numbers.";
    if ((poly & mask(w)) === 0n) return "The polynomial can't be zero.";
    const msg = String(v.message ?? "");
    if (!msg.length || msg.length > 32) return "The test message is 1 to 32 characters.";
    const bytes = [...msg].map((ch) => ch.charCodeAt(0) & 0xff);
    const xo = xorout & mask(w), mod = `crc${w}`;
    const design = `${header(`${w}-bit CRC, polynomial ${lit(w, poly)}, one bit per clock (MSB first, not reflected).`)}module ${mod} #(parameter [${w - 1}:0] INIT = ${lit(w, init)}) (
    input  wire        clk,
    input  wire        rst,        // synchronous, active high: start a new message
    input  wire        en,         // din is valid this cycle
    input  wire        din,        // message bits, most significant bit of each byte first
    output reg  ${decl(w)}crc,
    output wire ${decl(w)}crc_out    // the CRC to send: crc ^ XOROUT
);
    localparam [${w - 1}:0] POLY = ${lit(w, poly)}, XOROUT = ${lit(w, xo)};
    wire feedback = crc[${w - 1}] ^ din;
    always @(posedge clk)
        if (rst)     crc <= INIT;
        else if (en) crc <= {crc[${w - 2}:0], 1'b0} ^ (feedback ? POLY : ${w}'h0);
    assign crc_out = crc ^ XOROUT;
endmodule
`;
    const states = crcBits(bytes, w, poly, init);
    let c = init & mask(w), k = 0;
    const cycles: Cycle[] = [{ set: { rst: 1n, en: 0n, din: 0n }, expect: { crc: c, crc_out: c ^ xo }, note: "reset" }];
    bytes.forEach((byte, bi) => {
      for (let b = 7; b >= 0; b--, k++) {
        c = states[k];
        cycles.push({ set: { rst: 0n, en: 1n, din: big((byte >> b) & 1) }, expect: { crc: c, crc_out: c ^ xo }, note: b === 7 ? `byte ${bi}: 8'h${byte.toString(16)}` : undefined });
      }
      if (bi % 3 === 2) cycles.push({ set: { rst: 0n, en: 0n, din: 1n }, expect: { crc: c, crc_out: c ^ xo }, note: "en = 0: hold" });
    });
    return {
      module: mod, design,
      testbench: vectorTb(mod, [{ name: "rst", width: 1 }, { name: "en", width: 1 }, { name: "din", width: 1 }], [{ name: "crc", width: w }, { name: "crc_out", width: w }], cycles, true, `the CRC of "${msg}"`),
      notes: [`CRC of "${msg}" = ${lit(w, c ^ xo)}.`, "Reflected CRCs (the CRC-32 of Ethernet and zip) feed each byte LSB first and reverse the result."],
    };
  },
};

