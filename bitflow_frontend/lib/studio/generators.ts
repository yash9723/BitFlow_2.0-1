// ── ROM ──────────────────────────────────────────────────────────────────────

export function parseRomValues(text: string): bigint[] | string {
  const items = text.split(/[\s,;]+/).filter(Boolean);
  if (!items.length) return "List the ROM's words, such as 0x3F 0x06 0x5B.";
  if (items.length > 1024) return "Up to 1024 words.";
  const out: bigint[] = [];
  for (const it of items) {
    const t = it.replace(/_/g, "");
    if (/^0x[0-9a-f]+$/i.test(t) || /^0b[01]+$/i.test(t) || /^\d+$/.test(t)) out.push(BigInt(t));
    else return `"${it}" isn't a number (use 12, 0x0C or 0b1100).`;
  }
  return out;
}

