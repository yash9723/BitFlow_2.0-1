// ── Debouncer ────────────────────────────────────────────────────────────────

const debouncer: Generator = {
  id: "debounce", title: "Button debouncer", blurb: "Synchronises a button or switch (two flip-flops) and changes the output only after the input has been steady for N cycles.",
  params: [{ key: "n", label: "Steady cycles N", kind: "int", default: 4, min: 1, max: 1000000, hint: "For a real button about 10 ms: 1000000 at 100 MHz." }],
  build: (v) => {
    const n = num(v, "n");
    if (!(Number.isInteger(n) && n >= 1 && n <= 1_000_000)) return "N from 1 to 1000000.";
    const cw = bitsFor(Math.max(1, n - 1)), mod = "debounce";
    const design = `${header(`debouncer: clean follows noisy once it has been steady for ${n} cycle${n === 1 ? "" : "s"}.`)}module ${mod} (
    input  wire clk,
    input  wire rst,        // synchronous, active high
    input  wire noisy,      // straight from the pin: asynchronous and bouncy
    output reg  clean
);
    reg s0, s1;             // two-flip-flop synchroniser
    reg [${cw - 1}:0] cnt;
    always @(posedge clk)
        if (rst) begin s0 <= 1'b0; s1 <= 1'b0; cnt <= 0; clean <= 1'b0; end
        else begin
            s0 <= noisy;
            s1 <= s0;
            if (s1 == clean)                 cnt <= 0;            // nothing pending
            else if (cnt == ${cw}'d${n - 1}) begin clean <= s1; cnt <= 0; end
            else                             cnt <= cnt + 1'b1;
        end
endmodule
`;
    const r = rng(7);
    const stim: number[] = [0, 0];
    let level = 0;
    const want = Math.min(Math.max(120, 6 * n + 40), 400);
    while (stim.length < want) {
      level ^= 1;
      for (let b = 0; b < 6; b++) stim.push(r() < 0.5 ? level : level ^ 1);                      // bouncing
      for (let s = 0, m = n + 4 + Math.floor(r() * 6); s < m; s++) stim.push(level);             // settled
    }
    const cycles: Cycle[] = [];
    let s0 = 0, s1 = 0, cnt = 0, clean = 0;
    stim.forEach((x, i) => {
      const rst = i < 2;
      if (rst) { s0 = 0; s1 = 0; cnt = 0; clean = 0; }
      else {
        const old1 = s1;                                                                          // the always block sees the old s1
        s1 = s0; s0 = x;
        if (old1 === clean) cnt = 0;
        else if (cnt === n - 1) { clean = old1; cnt = 0; }
        else cnt++;
      }
      cycles.push({ set: { rst: rst ? 1n : 0n, noisy: big(x) }, expect: { clean: big(clean) } });
    });
    return {
      module: mod, design, testbench: vectorTb(mod, [{ name: "rst", width: 1 }, { name: "noisy", width: 1 }], [{ name: "clean", width: 1 }], cycles, true, "bouncing presses and releases"),
      notes: [`The output lags the input by 2 (synchroniser) + ${n} cycles.`],
    };
  },
};

// ── FIFO ─────────────────────────────────────────────────────────────────────

const fifo: Generator = {
  id: "fifo", title: "Synchronous FIFO", blurb: "A first-in first-out queue in one clock domain, with full, empty and a count. Writes when full and reads when empty are ignored.",
  params: [{ key: "width", label: "Data width", kind: "int", default: 8, min: 1, max: 64 }, { key: "depth", label: "Depth (power of 2)", kind: "int", default: 4, min: 2, max: 4096 }],
  build: (v) => {
    const w = num(v, "width"), depth = num(v, "depth");
    if (!(Number.isInteger(w) && w >= 1 && w <= 64)) return "Data widths from 1 to 64.";
    if (!isPow2(depth) || depth < 2 || depth > 4096) return "The depth is a power of two from 2 to 4096.";
    const aw = Math.log2(depth), cw = bitsFor(depth), mod = "fifo";
    const design = `${header(`synchronous FIFO, ${depth} words of ${w} bits.`)}module ${mod} (
    input  wire        clk,
    input  wire        rst,        // synchronous, active high: empty the FIFO
    input  wire        wr_en,
    input  wire ${decl(w)}din,
    input  wire        rd_en,
    output reg  ${decl(w)}dout,      // the word read, valid the cycle after rd_en
    output wire        full,
    output wire        empty,
    output reg  ${decl(cw)}count
);
    reg ${decl(w)}mem [0:${depth - 1}];
    reg [${aw - 1}:0] wp, rp;
    wire wr = wr_en && !full;
    wire rd = rd_en && !empty;
    always @(posedge clk)
        if (rst) begin wp <= 0; rp <= 0; count <= 0; dout <= 0; end
        else begin
            if (wr) begin mem[wp] <= din; wp <= wp + 1'b1; end
            if (rd) begin dout <= mem[rp]; rp <= rp + 1'b1; end
            if (wr && !rd)      count <= count + 1'b1;
            else if (rd && !wr) count <= count - 1'b1;
        end
    assign full  = (count == ${cw}'d${depth});
    assign empty = (count == 0);
endmodule
`;
    const r = rng(3), q: bigint[] = [], cycles: Cycle[] = [];
    let dout = 0n;
    const total = Math.min(Math.max(80, 6 * depth), 400), phaseLen = Math.max(8, 2 * depth);
    for (let i = 0; i < total; i++) {
      const rst = i < 2, draining = Math.floor(i / phaseLen) % 2 === 1;                          // fill, then drain, then fill…
      const wrEn = r() < (draining ? 0.3 : 0.75), rdEn = r() < (draining ? 0.75 : 0.3);
      const din = big(Math.floor(r() * 2 ** Math.min(w, 30))) & mask(w);
      if (rst) { q.length = 0; dout = 0n; }
      else {
        const wr = wrEn && q.length < depth, rd = rdEn && q.length > 0;
        if (rd) dout = q.shift()!;
        if (wr) q.push(din);
      }
      cycles.push({
        set: { rst: rst ? 1n : 0n, wr_en: wrEn ? 1n : 0n, din, rd_en: rdEn ? 1n : 0n },
        expect: { dout, full: q.length === depth ? 1n : 0n, empty: q.length === 0 ? 1n : 0n, count: big(q.length) },
      });
    }
    return {
      module: mod, design,
      testbench: vectorTb(mod, [{ name: "rst", width: 1 }, { name: "wr_en", width: 1 }, { name: "din", width: w }, { name: "rd_en", width: 1 }],
        [{ name: "dout", width: w }, { name: "full", width: 1 }, { name: "empty", width: 1 }, { name: "count", width: cw }], cycles, true, "random writes and reads that fill and drain it"),
      notes: ["dout is registered: it shows the word one cycle after rd_en.", `count needs ${cw} bits because it reaches ${depth}.`],
    };
  },
};

