/**
 * lib/studio/sv.ts — the SystemVerilog spelling of the Verilog the Studio tools generate
 * (components/studio/GeneratedCode.tsx "SystemVerilog" toggle): logic instead of wire/reg,
 * always_ff / always_comb, and a typedef enum for an FSM's states. It rewrites only the
 * patterns those generators emit; it is not a general Verilog-to-SV translator.
 * Simulated on Icarus (-g2012) by scripts/studio-sim.check.ts; unit checks in scripts/generators.check.ts.
 */

export function toSystemVerilog(verilog: string): string {
  let s = verilog
    // FSM state encodings: localparam [n:0] A = …, B = …;  reg [n:0] state, next_state;
    .replace(/localparam (\[[^\]]+\]) ([\s\S]*?);\n(\s*\n)*(\s*)reg \1 state, next_state;/g,
      (_m, range: string, list: string, _blank: string, ind: string) =>
        `typedef enum logic ${range} {\n${ind}    ${list.split(",").map((x) => x.trim()).join(`,\n${ind}    `)}\n${ind}} state_t;\n\n${ind}state_t state, next_state;`)
    .replace(/\b(input|output)(\s+)(wire|reg)( *)/g,                  // keep the columns lined up
      (_m, dir: string, sp: string, kw: string, pad: string) => `${dir}${sp}logic${" ".repeat(Math.max(1, kw.length + pad.length - 5))}`)
    .replace(/\balways\s*@\s*\(\s*\*\s*\)|\balways\s*@\s*\*/g, "always_comb")
    .replace(/\balways(\s*@\s*\(\s*(?:posedge|negedge)\b)/g, "always_ff$1");
  // declarations: reg -> logic; wire -> logic unless it has an initial value (that's a continuous assignment)
  s = s.split("\n").map((line) => {
    const m = /^(\s*)(reg|wire)\b(.*)$/.exec(line);
    if (!m || (m[2] === "wire" && m[3].includes("="))) return line;
    return `${m[1]}logic${m[3]}`;
  }).join("\n");
  return s.replace(/^\/\/ Generated by BitFlow Studio/m, "// Generated by BitFlow Studio (SystemVerilog)");
}
