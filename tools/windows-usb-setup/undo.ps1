# Removes the WinUSB driver that setup.cmd (or Zadig) put on USB 0403:6010 interface 0, and the
# certificate libwdi created for it; Windows then reinstalls the board's FTDI driver.
$ErrorActionPreference = "Continue"
$removed = 0
foreach ($d in Get-PnpDevice | Where-Object { $_.InstanceId -like 'USB\VID_0403&PID_6010&MI_00*' }) {
  $svc = (Get-PnpDeviceProperty -InstanceId $d.InstanceId -KeyName DEVPKEY_Device_Service -ErrorAction SilentlyContinue).Data
  $inf = (Get-PnpDeviceProperty -InstanceId $d.InstanceId -KeyName DEVPKEY_Device_DriverInfPath -ErrorAction SilentlyContinue).Data
  if ($svc -eq 'WinUSB' -and $inf -like 'oem*.inf') {
    Write-Host "Removing $inf from $($d.FriendlyName)"
    pnputil /delete-driver $inf /uninstall /force | Out-Host
    $removed++
  }
}
foreach ($store in 'Root', 'TrustedPublisher') {
  Get-ChildItem "Cert:\LocalMachine\$store" |
    Where-Object { $_.Subject -like '*VID_0403&PID_6010&MI_00 (libwdi autogenerated)*' } |
    ForEach-Object { Write-Host "Removing certificate $($_.Subject) from $store"; Remove-Item $_.PSPath }
}
pnputil /scan-devices | Out-Host
if ($removed -eq 0) { Write-Host "No WinUSB driver was installed on the board's programming interface." }
Start-Sleep -Seconds 3
exit 0
